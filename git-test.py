# small script for practicing Git commands
# demonstrate basic Python output with print statements
# store simple ASCII designs in multi-line strings
# display the designs in the terminal for a quick visual result

# print a simple greeting so the first commit has visible output
print("Hello from my Git practice file!")

# Store the ASCII-art version of the word "Hello!" in a multi-line string
hello_art = r"""
 #   #  ######  #       #        ###  
 #   #  #       #       #       #   # 
 #####  #####   #       #       #     
 #   #  #       #       #       #   # 
 #   #  ######  ######  ######   ###  
                                      
"""

# print a heading before showing the ASCII art
print("\nASCII art:")

# print the completed ASCII-art greeting
print(hello_art)

